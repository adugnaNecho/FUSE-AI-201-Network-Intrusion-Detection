#!/usr/bin/env python3
"""Evaluate saved live Windows predictions against separately adjudicated labels."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from windows_nids.model_training import classification_metrics
from windows_nids.schema import SCHEMA_VERSION


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--predictions", type=Path, required=True, help="windows_predictions.jsonl")
    parser.add_argument("--labels", type=Path, required=True, help="CSV with snapshot_id, session_id, label and label_source")
    parser.add_argument("--metadata", type=Path, default=Path("artifacts/windows_nids_model.json"))
    parser.add_argument("--output", type=Path, default=Path("artifacts/windows_nids_live_evaluation.json"))
    parser.add_argument("--positive-label", default=None, help="Optional positive class for binary ROC-AUC and PR-AUC")
    return parser.parse_args()


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    with path.open("r", encoding="utf-8-sig") as source:
        for line_number, line in enumerate(source, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON in predictions file at line {line_number}.") from exc
            if not isinstance(row, dict) or not row.get("snapshot_id"):
                raise ValueError(f"Prediction row {line_number} has no snapshot_id.")
            rows.append(row)
    return rows


def main() -> int:
    args = parse_args()
    try:
        for path in (args.predictions, args.labels, args.metadata):
            if not path.is_file():
                raise ValueError(f"Required input file not found: {path}")
        metadata = json.loads(args.metadata.read_text(encoding="utf-8"))
        if metadata.get("schema_version") != SCHEMA_VERSION:
            raise ValueError("Model metadata uses an incompatible Windows feature schema.")
        classes = metadata.get("classes")
        if not isinstance(classes, list) or len(classes) < 2:
            raise ValueError("Model metadata has no valid class list.")

        predictions = pd.DataFrame(read_jsonl(args.predictions))
        labels = pd.read_csv(args.labels, dtype=str)
        required = {"snapshot_id", "session_id", "label", "label_source"}
        missing = sorted(required - set(labels.columns))
        if missing:
            raise ValueError(f"Labels CSV is missing columns: {', '.join(missing)}")
        if predictions.empty:
            raise ValueError("Predictions file contains no prediction rows.")
        if predictions["snapshot_id"].astype(str).duplicated().any():
            raise ValueError("Predictions contain duplicate snapshot_id values.")
        if labels["snapshot_id"].astype(str).duplicated().any():
            raise ValueError("Labels contain duplicate snapshot_id values.")

        labels["snapshot_id"] = labels["snapshot_id"].fillna("").astype(str).str.strip()
        predictions["snapshot_id"] = predictions["snapshot_id"].fillna("").astype(str).str.strip()
        if (labels["snapshot_id"] == "").any() or (predictions["snapshot_id"] == "").any():
            raise ValueError("snapshot_id cannot be blank in the predictions or labels files.")
        expected_model_version = str(metadata.get("model_version", ""))
        if not expected_model_version or "model_version" not in predictions.columns:
            raise ValueError("Predictions must include model_version and metadata must declare it.")
        observed_versions = set(predictions["model_version"].fillna("").astype(str))
        if observed_versions != {expected_model_version}:
            raise ValueError(
                "Predictions file contains a different or mixed model_version. "
                "Use predictions generated by the model described by the supplied metadata."
            )
        labels["label"] = labels["label"].fillna("").astype(str).str.strip()
        labels["label_source"] = labels["label_source"].fillna("").astype(str).str.strip()
        labels["session_id"] = labels["session_id"].fillna("").astype(str).str.strip()
        labels = labels[(labels["label"] != "") & (labels["label_source"] != "") & (labels["session_id"] != "")]
        matched = labels.merge(predictions, on="snapshot_id", how="inner", validate="one_to_one", suffixes=("_truth", "_prediction"))
        if matched.empty:
            raise ValueError("No labelled snapshots matched prediction snapshot_id values.")

        reserved_groups = set(str(v) for v in metadata.get("training_groups", []))
        reserved_groups.update(str(v) for v in metadata.get("holdout_groups", []))
        evaluation_groups = set(matched["session_id"].astype(str))
        overlap = sorted(reserved_groups & evaluation_groups)
        if overlap:
            raise ValueError(
                "Live evaluation sessions overlap model-development sessions (training or internal holdout). "
                "Use a new, independently labelled capture session that was not used for model fitting or selection. "
                f"Overlapping session IDs: {overlap[:5]}"
            )

        y_true = matched["label"].astype(str).to_numpy()
        y_pred = matched["predicted_class"].astype(str).to_numpy()
        unknown = sorted((set(y_true) | set(y_pred)) - set(classes))
        if unknown:
            raise ValueError(f"Labels/predictions contain classes absent from model metadata: {unknown}")
        probability_rows = []
        for item in matched["class_probabilities"]:
            if not isinstance(item, dict):
                raise ValueError("A prediction row has no class_probabilities object.")
            probability_rows.append([float(item.get(label, np.nan)) for label in classes])
        probabilities = np.asarray(probability_rows, dtype=float)
        if not np.isfinite(probabilities).all():
            raise ValueError("Some predictions are missing finite per-class probability values.")

        metrics = classification_metrics(y_true, y_pred, probabilities, classes, args.positive_label)
        report = {
            "schema_version": SCHEMA_VERSION,
            "evaluation_type": "independent_live_predictions",
            "model_version": metadata.get("model_version", "unknown"),
            "model_sha256": metadata.get("model_sha256"),
            "label_sources": sorted(matched["label_source"].unique().tolist()),
            "independent_sessions": sorted(evaluation_groups),
            "prediction_rows_total": int(len(predictions)),
            "labelled_rows_available": int(len(labels)),
            "matched_evaluation_rows": int(len(matched)),
            "unlabelled_or_unmatched_predictions": int(len(predictions) - len(matched)),
            "labelled_rows_without_prediction": int(len(labels) - len(matched)),
            "metrics": metrics,
            "evaluation_note": "Metrics apply only to matched, independently labelled snapshots; unlabelled predictions are not counted as correct or incorrect.",
        }
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        print(f"Independent live evaluation saved: {args.output}")
        print(json.dumps(report, indent=2))
        return 0
    except (ValueError, OSError, json.JSONDecodeError, KeyError, TypeError) as exc:
        print(f"Live evaluation stopped: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
